#!/usr/bin/env node
/**
 * Bundles xterm.js + its fit addon into a TypeScript module as strings, so the
 * terminal WebView works offline with no CDN. Re-run after upgrading xterm:
 *   npm run gen-terminal
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const read = (p) => fs.readFileSync(path.join(root, 'node_modules', p), 'utf8');

const js = read('@xterm/xterm/lib/xterm.js');
const fit = read('@xterm/addon-fit/lib/addon-fit.js');
const css = read('@xterm/xterm/css/xterm.css');
const version = JSON.parse(read('@xterm/xterm/package.json')).version;

const out = `// GENERATED by scripts/gen-terminal-assets.js – do not edit.
// xterm.js ${version} (MIT licence, https://github.com/xtermjs/xterm.js)
export const XTERM_JS = ${JSON.stringify(js)};
export const XTERM_FIT_JS = ${JSON.stringify(fit)};
export const XTERM_CSS = ${JSON.stringify(css)};
`;

const target = path.join(root, 'src', 'terminal', 'xtermAssets.generated.ts');
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, out);
console.log(`Wrote ${path.relative(root, target)} (${Math.round(out.length / 1024)} KB)`);
